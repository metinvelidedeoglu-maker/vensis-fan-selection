import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)('playwright');
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const id='AXD|AXD 35-4M-0.18|2860|27';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH||undefined,headless:true,args:['--no-sandbox']});
const context=await browser.newContext(),errors=[];
context.on('page',page=>page.on('pageerror',e=>errors.push(e.message)));
await context.route('**/*',async route=>{
  const u=new URL(route.request().url());if(u.hostname!=='vensis.test')return route.abort();
  const f=path.resolve(root,'.'+decodeURIComponent(u.pathname).replace(/^\/(?:tr|en)\//,'/'));
  if(!f.startsWith(root+'/')||!fs.existsSync(f)||!fs.statSync(f).isFile())return route.fulfill({status:404,body:'Not found'});
  const type={'.html':'text/html','.js':'application/javascript','.css':'text/css','.png':'image/png','.webp':'image/webp','.jpg':'image/jpeg','.json':'application/json'}[path.extname(f)]||'application/octet-stream';
  await route.fulfill({status:200,contentType:type,body:fs.readFileSync(f)});
});
await context.addInitScript(()=>{if(location.origin==='null')return;localStorage.setItem('vensis_access_mode_v1','guest');localStorage.setItem('vensis_language_v1','tr');});
try{
  const page=await context.newPage();
  await page.goto('http://vensis.test/projects.html');
  await page.waitForFunction(()=>Boolean(window.VensisProjects?.create));
  const project=await page.evaluate(()=>window.VensisProjects.create({name:'AXD verification fixture'}).id);
  await page.goto('http://vensis.test/catalog.html?series=AXD&model='+encodeURIComponent(id)+'&project='+encodeURIComponent(project));
  const card=page.locator('.model-card:not([hidden])');await card.locator('.vensis-preview-classic').waitFor();
  assert.equal(await card.count(),1);
  assert.match(await card.innerText(),/AXD 35-4M-0\.18/);
  assert.match(await card.innerText(),/600[,.]00/);
  assert.match(await card.innerText(),/Monofaze/);
  assert.match(await card.innerText(),/230V/);
  assert.doesNotMatch(await card.innerText(),/ATEX/);
  const tr=await page.evaluate(id=>window.VensisDirectPreview.html({product:window.VensisCatalog.product(id),model:window.VensisCatalog.getModel(id),outputLanguage:'tr'}),id);
  const en=await page.evaluate(id=>window.VensisDirectPreview.html({product:window.VensisCatalog.product(id),model:window.VensisCatalog.getModel(id),outputLanguage:'en'}),id);
  assert.match(tr,/Monofaze 230 V, 50 Hz, 4 kutuplu motor/);
  assert.match(en,/Single-phase 230 V, 50 Hz, 4-pole motor/);
  for(const preview of [tr,en])assert.doesNotMatch(preview,/400\s*V|frequency converter/);
  await card.locator('[data-add-catalog-project]').click();
  await page.locator('#catalogProjectModal:not([hidden])').waitFor();
  await page.locator('input[name="catalogProjectChoice"][value="'+project+'"]').check();
  await page.locator('#catalogProjectConfirm').click();
  await page.waitForURL(url=>url.pathname.endsWith('/project.html'));
  await page.locator('#projectContent tbody tr').first().waitFor();
  const items=await page.evaluate(id=>window.VensisProjects.readItems(id),project);
  assert.equal(items.length,1);assert.equal(items[0].productKey,id);assert.equal(items[0].price,600);
  assert.equal(items[0].voltage,'230V');assert.equal(items[0].hazardousArea??null,null);
  const pending=context.waitForEvent('page');await page.locator('#convertQuotation').click();
  const quote=await pending;await quote.locator('#quotationContent .quote-page').first().waitFor();
  const body=await quote.locator('#quotationContent').innerText();
  assert.match(body,/AXD 35-4M-0\.18/);assert.match(body,/600[,.]00/);assert.doesNotMatch(body,/ATEX/);
  assert.deepEqual(errors,[]);
  console.log('PASS: AXD Turkish card, bilingual preview, project addition and EUR 600 quotation.');
}finally{await browser.close();}
